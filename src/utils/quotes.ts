/**
 * Deterministically returns the quote of the day based on current date (YYYY-MM-DD)
 * and active language preference.
 */
export function getQuoteOfDay(dateStr?: string, lang: string = "en"): Quote {
  const d = dateStr ? new Date(dateStr) : new Date();
  const startOfYear = new Date(d.getFullYear(), 0, 0);
  const diff = d.getTime() - startOfYear.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  
  const index = Math.abs(dayOfYear) % DAILY_QUOTES.length;
  const cleanLang = (lang || "en").toLowerCase();

  if (LOCALIZED_QUOTES[cleanLang] && LOCALIZED_QUOTES[cleanLang][index]) {
    return LOCALIZED_QUOTES[cleanLang][index];
  }

  return DAILY_QUOTES[index];
}
